#!/usr/bin/env python3
"""
glyph_tool.py - helper for the Glyph Editor.

  python glyph_tool.py normalize <input_folder> <output_folder> [--size 96] [--color 000000]
      Cleans your raw glyph pictures: trims the empty border, centres each glyph in a
      square, makes the white background transparent, and saves small PNGs.
      (Needs:  pip install pillow)

  python glyph_tool.py pack <glyph_folder> <output_header.h>
      Reads <glyph_folder>/glyphs.txt and packs it plus every PNG it mentions into one
      C++ header, so the editor can be built as ONE portable .exe (no loose files).
"""
import os, sys, argparse

def normalize(src, dst, size, color):
    from PIL import Image
    os.makedirs(dst, exist_ok=True)
    r, g, b = (int(color[i:i+2], 16) for i in (0, 2, 4))
    exts = ('.png', '.jpg', '.jpeg', '.bmp', '.gif')
    files = sorted(f for f in os.listdir(src) if f.lower().endswith(exts))
    if not files:
        print("No pictures found in", src); return
    for f in files:
        im = Image.open(os.path.join(src, f)).convert('RGBA')
        bg = Image.new('RGBA', im.size, (255, 255, 255, 255))
        bg.alpha_composite(im)                       # flatten onto white
        gray = bg.convert('L')
        box = gray.point(lambda v: 255 if v < 250 else 0).getbbox()
        if box is None:
            print("skip (empty):", f); continue
        gray = gray.crop(box)
        alpha = gray.point(lambda v: 255 - v)        # dark ink -> opaque, white -> clear
        w, h = alpha.size
        side = int(max(w, h) * 1.16)                 # 8% margin each side
        canvas = Image.new('L', (side, side), 0)
        canvas.paste(alpha, ((side - w) // 2, (side - h) // 2))
        canvas = canvas.resize((size, size), Image.LANCZOS)
        out = Image.new('RGBA', (size, size), (r, g, b, 0))
        out.putalpha(canvas)
        name = os.path.splitext(f)[0] + '.png'
        out.save(os.path.join(dst, name), optimize=True)
        print("ok:", name)

def referenced_files(folder):
    names = ['glyphs.txt']
    with open(os.path.join(folder, 'glyphs.txt'), encoding='utf-8-sig') as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith('#') or line.startswith('@') or '=' not in line:
                continue
            right = line.split('=', 1)[1]
            if ' #' in right:
                right = right.split(' #', 1)[0]
            right = right.strip()
            if right and right not in names:
                names.append(right)
    return names

def pack(folder, header):
    names = referenced_files(folder)
    lines = ["// AUTO-GENERATED by tools/glyph_tool.py pack  -  do not edit by hand.",
             "#pragma once",
             "struct EmbeddedFile { const char* name; const unsigned char* data; unsigned int size; };", ""]
    total = 0
    for i, n in enumerate(names):
        p = os.path.join(folder, n)
        if not os.path.exists(p):
            print("WARNING: missing file", n); data = b''
        else:
            data = open(p, 'rb').read()
        total += len(data)
        lines.append("static const unsigned char kFile%d[] = {" % i)
        for k in range(0, len(data), 16):
            lines.append("  " + ",".join("0x%02x" % c for c in data[k:k+16]) + ",")
        if not data:
            lines.append("  0x00")
        lines.append("};")
    lines.append("static const EmbeddedFile kEmbeddedFiles[] = {")
    for i, n in enumerate(names):
        lines.append('  { "%s", kFile%d, sizeof(kFile%d) },' % (n, i, i))
    lines.append("};")
    lines.append("static const unsigned int kEmbeddedFileCount = %d;" % len(names))
    open(header, 'w').write("\n".join(lines) + "\n")
    print("packed %d files, %d bytes -> %s" % (len(names), total, header))

if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    n = sub.add_parser('normalize'); n.add_argument('src'); n.add_argument('dst')
    n.add_argument('--size', type=int, default=96); n.add_argument('--color', default='000000')
    k = sub.add_parser('pack'); k.add_argument('folder'); k.add_argument('header')
    a = ap.parse_args()
    if a.cmd == 'normalize': normalize(a.src, a.dst, a.size, a.color)
    else: pack(a.folder, a.header)
